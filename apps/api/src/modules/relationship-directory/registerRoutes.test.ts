import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import type { AddressInfo } from 'node:net';
import express from 'express';
import { SignJWT } from 'jose';
import { PGlite } from '@electric-sql/pglite';
import { BrokerSchema, registerRelationshipDirectory } from './registerRoutes';
import { createProspectContact, updateProspectContact } from '../../lib/prospectContactService';
import { DirectoryContextSchema } from './context';
test('directory persistence, ownership, validation, concurrent edits, and merged accounts', async (t) => {
    const db = new PGlite();
    t.after(() => db.close());
    const fixture = await readFile(new URL('../../lib/prospectContactService.test.ts', import.meta.url), 'utf8');
    const quote = String.fromCharCode(96);
    await db.exec(fixture.split('const schema = ' + quote)[1].split(quote + ';')[0]);
    await db.exec('ALTER TABLE prospects ADD COLUMN merge_event_id varchar; CREATE TABLE prospect_merge_events(id varchar,preview_hash varchar)');
    for (const migration of ['0021_prospect_contacts.sql', '0023_relationship_directory.sql','0024_relationship_graph.sql']) {
        await db.exec(await readFile(new URL('../../../../../drizzle/' + migration, import.meta.url), 'utf8'));
    }
    let tail = Promise.resolve();
    async function acquire() {
        const previous = tail;
        let release!: () => void;
        tail = new Promise<void>(resolve => { release = resolve; });
        await previous;
        return release;
    }
    const pool: any = {
        async query(sql: string, values?: unknown[]) { const release = await acquire(); try {
            return await db.query(sql, values);
        }
        finally {
            release();
        } },
        async connect() { const release = await acquire(); return { query: (sql: string, values?: unknown[]) => db.query(sql, values), release }; },
    };
    const secret = randomUUID();
    process.env.SUPABASE_JWT_SECRET = secret;
    const token = async (id: string) => 'Bearer ' + await new SignJWT({}).setProtectedHeader({ alg: 'HS256' }).setSubject(id)
        .setIssuer((process.env.VITE_SUPABASE_URL || process.env.SUPABASE_URL || 'http://localhost').replace(/\/$/, '') + '/auth/v1')
        .setExpirationTime('5m').sign(new TextEncoder().encode(secret));
    const owner = await token('owner'), foreign = await token('foreign');
    const agentKey = randomUUID();
    process.env.ACCOUNT_INTELLIGENCE_AGENT_API_KEY = agentKey;
    process.env.ACCOUNT_INTELLIGENCE_AGENT_USER_ID = 'owner';
    t.after(() => {delete process.env.ACCOUNT_INTELLIGENCE_AGENT_API_KEY;delete process.env.ACCOUNT_INTELLIGENCE_AGENT_USER_ID});
    const app = express();
    app.use(express.json());
    registerRelationshipDirectory(app, pool);
    const server = app.listen(0, '127.0.0.1');
    await new Promise<void>(resolve => server.once('listening', resolve));
    t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
    const url = 'http://127.0.0.1:' + (server.address() as AddressInfo).port + '/api/desk/directory';
    const call = (path: string, auth = owner, body?: unknown) => fetch(url + path, { method: body === undefined ? 'GET' : 'PUT', headers: { Authorization: auth, 'content-type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    assert.equal((await call('', '')).status, 401);
    let response = await call('');
    assert.equal(response.headers.get('cache-control'), 'no-store');
    assert.equal((await response.json()).companies.length, 2);
    const id = randomUUID(), relationshipId = randomUUID();
    const broker = { name: 'Test broker', firm: 'Cushman & Wakefield', email: 'broker@example.test', phone: '+1 780 555 0101', linkedinUrl: 'https://www.linkedin.com/in/test-broker', version: 0 };
    assert.equal(BrokerSchema.safeParse({ ...broker, linkedinUrl: 'not a url' }).success, false);
    assert.equal(BrokerSchema.safeParse({ ...broker, linkedinUrl: 'https://linkedin.com.evil.test/a' }).success, false);
    assert.equal((await call('/brokers/' + id, owner, { ...broker, userId: 'foreign' })).status, 400);
    assert.equal((await call('/brokers/' + id, owner, broker)).status, 200);
    assert.equal((await call('/brokers/' + id, foreign)).status, 404);
    assert.equal((await call('/brokers/' + id, foreign, { ...broker, version: 1 })).status, 409);
    const link = { brokerId: id, prospectId: 'account', status: 'historical', scope: 'Past local assignment', notes: 'Broker confirmed', sourceUrl: 'https://example.com/evidence', learnedOn: '2026-11-19', version: 0 };
    assert.equal((await call('/relationships/' + relationshipId, owner, link)).status, 200);
    assert.equal((await call('/relationships/' + randomUUID(), foreign, link)).status, 409);
    assert.equal((await call('/relationships/' + randomUUID(), owner, { ...link, prospectId: 'foreign-account' })).status, 409);
    assert.equal((await call('/relationships/' + randomUUID(), owner, link)).status, 409);
    assert.equal((await call('/relationships/' + relationshipId, owner, link)).status, 409);
    const contact = await createProspectContact({ pool, userId: 'owner', prospectId: 'account', input: { name: 'New contact', email: 'contact@example.test' } });
    assert.ok(contact.contacts.some(c => c.email === 'contact@example.test'));
    const company = await (await call('/companies/account')).json();
    assert.equal(company.relationships[0].brokerName, 'Test broker');
    assert.ok(company.contacts.some((c: any) => c.email === 'contact@example.test'));
    assert.equal((await call('/companies/foreign-account')).status, 404);
    const updates = await Promise.all([1, 2].map(n => call('/brokers/' + id, owner, { ...broker, name: 'Updated ' + n, version: 1 })));
    assert.deepEqual(updates.map(r => r.status).sort(), [200, 409]);
    const fresh = await (await call('/brokers/' + id)).json();
    assert.equal(fresh.broker.version, 2);
    assert.equal(fresh.relationships.length, 1);
    const agent = (path:string,body?:unknown,auth='Bearer '+agentKey) => fetch(url.replace('/api/desk/directory','/api/intel/directory')+path,{method:body===undefined?'GET':'POST',headers:{Authorization:auth,'content-type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
    const decide = (id:string,decision:string,auth=owner) => fetch(url+'/findings/'+id+'/review',{method:'POST',headers:{Authorization:auth,'content-type':'application/json'},body:JSON.stringify({decision})});
    const context = {roles:['director'],legalEntity:'Fixture Company Ltd.',jurisdiction:'Alberta',sourceType:'corporate_search',sourceRef:'Test fixture corporate search 2026-11-19',asOf:'2026-11-19',evidenceStatus:'observed'};
    assert.equal((await agent('/manifest')).status,200);
    assert.equal((await agent('/search?search=contact')).status,200);
    process.env.INTEL_AGENT_API_KEY = randomUUID();
    process.env.INTEL_AGENT_USER_ID = 'owner';
    process.env.SALES_ACTIVITY_AGENT_API_KEY = randomUUID();
    process.env.SALES_ACTIVITY_AGENT_USER_ID = 'owner';
    assert.equal((await agent('/companies/account/brief',undefined,'Bearer '+process.env.INTEL_AGENT_API_KEY)).status,403);
    assert.equal((await agent('/companies/account/brief',undefined,'Bearer '+process.env.SALES_ACTIVITY_AGENT_API_KEY)).status,403);
    for (const key of ['INTEL_AGENT_API_KEY','INTEL_AGENT_USER_ID','SALES_ACTIVITY_AGENT_API_KEY','SALES_ACTIVITY_AGENT_USER_ID']) delete process.env[key];
    assert.equal(DirectoryContextSchema.safeParse({...context,legalEntity:''}).success,false);
    assert.equal((await agent('/companies/account/brief')).status,200);
    assert.equal((await agent('/companies/foreign-account/brief')).status,404);
    assert.equal((await call('/companies/account','Bearer '+agentKey)).status,403);
    assert.equal((await call('/brokers/'+randomUUID(),'Bearer '+agentKey,broker)).status,403);
    const finding={externalKey:'fixture-director-one',prospectId:'account',contact:{name:'Fixture Director',directoryContext:context}};
    assert.equal((await agent('/findings',{...finding,userId:'foreign'})).status,400);
    assert.equal((await agent('/findings',{...finding,prospectId:'foreign-account'})).status,404);
    assert.equal((await agent('/findings',{...finding,contact:{...finding.contact,directoryContext:{...context,sourceRef:''}}})).status,400);
    const posted=await agent('/findings',finding);
    assert.equal(posted.status,200);
    const findingId=(await posted.json()).id;
    assert.equal((await (await agent('/findings',finding)).json()).id,findingId);
    assert.equal((await agent('/findings',{...finding,contact:{...finding.contact,name:'Different director'}})).status,409);
    let brief=await (await agent('/companies/account/brief')).json();
    assert.equal(brief.findings.length,1);
    assert.equal(brief.contacts.some((c:any)=>c.name==='Fixture Director'),false);
    assert.equal((await decide(findingId,'accepted','Bearer '+agentKey)).status,403);
    assert.equal((await decide(findingId,'accepted',foreign)).status,404);
    assert.equal((await decide(findingId,'accepted')).status,200);
    assert.equal((await (await decide(findingId,'accepted')).json()).duplicate,true);
    brief=await (await agent('/companies/account/brief')).json();
    const directors=brief.contacts.filter((c:any)=>c.name==='Fixture Director');
    assert.equal(directors.length,1);
    assert.equal(directors[0].directoryContext.legalEntity,context.legalEntity);
    assert.equal(directors[0].directoryContext.evidenceStatus,'observed');
    assert.equal(brief.coverage.find((r:any)=>r.role==='director').gap,false);
    assert.equal(brief.findings.length,0);
    const updated=await updateProspectContact({pool,userId:'owner',prospectId:'account',contactId:directors[0].id,input:{directoryContext:DirectoryContextSchema.parse({...context,roles:['director','finance'],evidenceStatus:'inferred'})}});
    assert.deepEqual(updated.contacts.find(c=>c.id===directors[0].id)?.directoryContext?.roles,['director','finance']);
    brief=await (await agent('/companies/account/brief')).json();
    assert.equal(brief.coverage.find((r:any)=>r.role==='finance').gap,true);
    assert.equal(brief.coverage.find((r:any)=>r.role==='director').gap,true);
    const pending2=await (await agent('/findings',{...finding,externalKey:'fixture-director-two',contact:{...finding.contact,name:'Unaccepted Director'}})).json();
    assert.equal((await decide(pending2.id,'rejected')).status,200);
    assert.equal((await decide(pending2.id,'accepted')).status,409);
    const mergingFinding=await (await agent('/findings',{...finding,externalKey:'fixture-merged-director',contact:{...finding.contact,name:'Director Before Merge'}})).json();
    await db.exec("UPDATE prospects SET merged_into_prospect_id='other-account' WHERE id='account'");
    const merged = await (await call('/companies/account')).json();
    assert.equal(merged.prospect.id, 'other-account');
    assert.equal(merged.relationships.length, 1);
    assert.equal(merged.findings.length,1);
    assert.equal(merged.findings[0].sourceProspectId,'account');
    assert.equal((await decide(mergingFinding.id,'accepted')).status,200);
    const afterMerge=await (await agent('/companies/other-account/brief')).json();
    assert.ok(afterMerge.contacts.some((c:any)=>c.name==='Director Before Merge'&&c.directoryContext.legalEntity===context.legalEntity));
    assert.equal((await call('/relationships/' + relationshipId, owner, { ...link, status: 'ended', version: 1 })).status, 200);
    assert.equal((await call('/relationships/' + relationshipId, owner, { ...link, version: 2, archived: true })).status, 200);
    assert.equal((await (await call('/brokers/' + id)).json()).relationships.length, 0);
    await db.exec('SET ROLE authenticated');
    await assert.rejects(db.query('SELECT * FROM directory_brokers'), /permission denied/);
    await assert.rejects(db.query('SELECT * FROM directory_relationships'), /permission denied/);
    await assert.rejects(db.query('SELECT * FROM directory_findings'), /permission denied/);
});
